def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def validate_checksums(directory: Path) -> None:
    for line in (directory / "checksums.sha256").read_text(encoding="utf-8").splitlines():
        expected, relative = line.split(maxsplit=1)
        assert sha256(directory / relative.strip()) == expected, relative


def independent_centered_maximin_lhs() -> np.ndarray:
    """Independently repeat the preregistered NumPy PCG64 construction."""
    rng = np.random.Generator(np.random.PCG64(20260830))
    centers = (np.arange(32, dtype=np.float64) + 0.5) / 32.0
    best: np.ndarray | None = None
    best_distance = -np.inf
    best_flat: tuple[float, ...] | None = None
    for _ in range(512):
        candidate = np.column_stack([centers[rng.permutation(32)] for _ in range(6)])
        delta = candidate[:, None, :] - candidate[None, :, :]
        distance = np.sqrt(np.sum(delta * delta, axis=2))
        minimum = float(np.min(distance[np.triu_indices(32, k=1)]))
        flat = tuple(candidate.ravel())
        if minimum > best_distance or (
            minimum == best_distance and (best_flat is None or flat < best_flat)
        ):
            best = candidate.copy()
            best_distance = minimum
            best_flat = flat
    assert best is not None
    return best


