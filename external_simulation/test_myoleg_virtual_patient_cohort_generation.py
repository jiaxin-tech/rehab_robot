def test_all_subject_identities_and_scheme_a_only_deltas_are_retained() -> None:
    manifest = read_json(ARTIFACTS / "MYOLEG_VIRTUAL_PATIENT_COHORT_V1_MANIFEST.json")
    assert len(manifest["subjects"]) == 32
    model_fingerprints = set()
    allowed_body_fields = {"body_mass", "body_inertia"}
    allowed_actuator_fields = {
        "actuator_gainprm_7_fpmax",
        "actuator_biasprm_7_fpmax",
    }
    for subject in manifest["subjects"]:
        directory = SUBJECTS / subject["subject_id"]
        delta = read_json(directory / "model_delta.json")
        metadata = read_json(directory / "metadata.json")
        assert tuple(delta["factor_order"]) == FACTORS
        assert delta["factor_values"] == subject["factor_values"]
        assert delta["unit_cube_vector"] == subject["unit_cube_vector"]
        assert delta["inertia_scaling_is_modeling_approximation"] is True
        assert delta["base_model_sha256"] == FROZEN[MODEL]
        assert delta["cohort_protocol_sha256"] == FROZEN[RANGES / "MYOLEG_VIRTUAL_PATIENT_COHORT_GENERATION_PROTOCOL_V1.json"]
        for change in delta["modifications"]:
            assert change["factor_id"] in FACTORS
            if change["object_type"] == "body":
                assert set(change["fields"]) <= allowed_body_fields
                assert change["body_ipos_com_unchanged"] is True
            else:
                assert change["object_type"] == "actuator"
                assert set(change["fields"]) <= allowed_actuator_fields
        checks = metadata["structure"]["checks"]
        assert all(checks.values())
        assert metadata["structure"]["dimensions"]["nu"] == 80
        assert metadata["structure"]["dimensions"]["ntendon"] == 80
        assert metadata["structure"]["pass"] is True
        model_fingerprints.add(metadata["generated_model_fingerprint_sha256"])
    assert len(model_fingerprints) == 32


def test_all_reference_replays_are_complete_finite_and_normalized() -> None:
    integrity = read_csv(ARTIFACTS / "SUBJECT_INTEGRITY_RESULTS.csv")
    normalization = read_csv(ARTIFACTS / "SUBJECT_REFERENCE_NORMALIZATION.csv")
    assert len(integrity) == len(normalization) == 32
    assert all(row["subject_integrity"] == "PASS" for row in integrity)
    assert all(row["replacement_sample"] == "False" for row in integrity)
    assert all(row["subject_specific_reference_normalization"] == "PASS" for row in normalization)
    assert all(row["nominal_denominator_used"] == "False" for row in normalization)
    for row in normalization:
        assert float(row["subject_reference_tau_hip_rms_nm"]) > 0.0
        assert float(row["subject_reference_tau_knee_rms_nm"]) > 0.0
        assert abs(float(row["j_truth_reference"]) - 1.0) <= 1.0e-12
        replay_path = SUBJECTS / row["subject_id"] / "reference_replay_truth.npz"
        with np.load(replay_path, allow_pickle=False) as replay:
            assert replay["time_s"].shape == (401,)
            assert replay["tau_truth_nm"].shape == (401, 2)
            assert replay["actuator_force_n"].shape == (401, 80)
            assert replay["tendon_length_m"].shape == (401, 80)
            assert replay["time_s"][0] == 0.0
            assert replay["time_s"][-1] == 24.0
            assert all(np.isfinite(replay[name]).all() for name in replay.files if replay[name].dtype.kind in "fciu")


