def test_literal_lhs_is_deterministic_centered_stratified_and_unique() -> None:
    rows = read_csv(ARTIFACTS / "LHS_UNIT_CUBE_MATRIX.csv")
    unit_columns = tuple(f"u_{index}_{factor}" for index, factor in enumerate(FACTORS, 1))
    matrix = np.asarray([[float(row[column]) for column in unit_columns] for row in rows])
    assert matrix.shape == (32, 6)
    assert np.array_equal(matrix, independent_centered_maximin_lhs())
    assert np.unique(matrix, axis=0).shape[0] == 32
    expected_centers = (np.arange(32, dtype=np.float64) + 0.5) / 32.0
    for column in matrix.T:
        assert np.array_equal(np.sort(column), expected_centers)
    audit = read_json(ARTIFACTS / "COHORT_COVERAGE_AUDIT.json")["overall_lhs"]
    assert audit["duplicate_row_count"] == 0
    assert audit["all_dimensions_centered_stratified"] is True


def test_transformed_matrix_uses_only_frozen_primary_bounds() -> None:
    unit_rows = read_csv(ARTIFACTS / "LHS_UNIT_CUBE_MATRIX.csv")
    parameter_rows = read_csv(ARTIFACTS / "SUBJECT_PARAMETER_MATRIX.csv")
    unit_columns = tuple(f"u_{index}_{factor}" for index, factor in enumerate(FACTORS, 1))
    unit = np.asarray([[float(row[column]) for column in unit_columns] for row in unit_rows])
    physical = np.asarray([[float(row[factor]) for factor in FACTORS] for row in parameter_rows])
    expected = PRIMARY_BOUNDS[:, 0] + unit * (PRIMARY_BOUNDS[:, 1] - PRIMARY_BOUNDS[:, 0])
    assert np.array_equal(physical, expected)
    assert np.all(physical >= PRIMARY_BOUNDS[:, 0])
    assert np.all(physical <= PRIMARY_BOUNDS[:, 1])
    manifest = read_json(ARTIFACTS / "MYOLEG_VIRTUAL_PATIENT_COHORT_V1_MANIFEST.json")
    assert manifest["extended_ranges_used"] is False


